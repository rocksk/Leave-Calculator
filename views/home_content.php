    <h2 class="text-2xl font-semibold text-slate-900 dark:text-white mt-12 mb-4">Additional Factors That Affect Leave Calculations</h2>
    <p class="leading-relaxed">Several factors may influence annual leave entitlements and should be considered when calculating leave balances.</p>

    <h3 class="text-xl font-medium text-slate-800 dark:text-slate-200 mt-6 mb-3">Leave Loading</h3>
    <p class="leading-relaxed">Leave loading is an additional payment made to employees while they are on annual leave. It is commonly set at 17.5% of the employee's ordinary pay rate, although the exact amount may vary depending on workplace agreements or industry awards.</p>
    <p class="leading-relaxed">The purpose of leave loading is to compensate employees for overtime opportunities and other allowances they may miss while away from work.</p>

    <h3 class="text-xl font-medium text-slate-800 dark:text-slate-200 mt-6 mb-3">Unused Annual Leave</h3>
    <p class="leading-relaxed">Unused annual leave is often carried forward into future years unless workplace policies specify otherwise.</p>
    <p class="leading-relaxed">In some cases, employees may be allowed to cash out a portion of their unused leave, provided legal requirements and workplace agreements permit this arrangement.</p>
    <p class="leading-relaxed">Maintaining accurate leave records is essential to ensure leave balances remain correct and up to date.</p>

